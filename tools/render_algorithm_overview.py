"""Build the offline, fixed-light algorithm document from its editable fragment."""
import argparse
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "docs/assets/algorithm-overview.fragment.html"
BASE_CSS = ROOT / "docs/assets/algorithm-overview-base.css"
OUTPUT = ROOT / "docs/design/algorithm-overview.html"


def render():
    css = BASE_CSS.read_text(encoding="utf-8")
    fragment = SOURCE.read_text(encoding="utf-8").strip()
    return """<!doctype html>
<html lang="zh-CN" data-theme="light">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="color-scheme" content="light">
  <meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'unsafe-inline'; style-src 'unsafe-inline'; img-src data:; base-uri 'none'; form-action 'none'">
  <title>BridgeVLA · 算法全景与动作流程</title>
  <!-- Generated by tools/render_algorithm_overview.py; edit the source fragment. -->
  <style>
""" + css + """
  :root[data-theme="light"] {
    color-scheme: light;
    --font-size-base: 16px;
    --font-weight-normal: 400;
    --font-sans: -apple-system, system-ui, "Segoe UI", "PingFang SC", "Microsoft YaHei", sans-serif;
    --muted-foreground: color-mix(in srgb, var(--foreground) 70%, var(--background));
  }
  body { margin: 0; padding: 0; background: var(--background); color: var(--foreground); }
  </style>
</head>
<body>
""" + fragment + """
<noscript>请启用 JavaScript 以查看交互流程和逐步骤完整说明；静态符号表、训练说明和函数索引仍可阅读。</noscript>
</body>
</html>
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if the generated HTML is stale")
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != expected:
            parser.exit(1, "Algorithm overview is stale; run python tools/render_algorithm_overview.py\n")
        print("Algorithm overview is up to date.")
        return 0
    with OUTPUT.open("w", encoding="utf-8", newline="\n") as stream:
        stream.write(expected)
    print("Rendered docs/design/algorithm-overview.html")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
